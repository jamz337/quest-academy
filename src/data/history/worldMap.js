function inside(poly, lon, lat) {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
}

/** Which part of the world a point is in: the land it is on, else the Caribbean if it is in that box, else null. */
export function landAt(lon, lat) {
  for (const land of LANDS) if (land.polys.some((p) => inside(p, lon, lat))) return land.name;
  const [w, s, e, n] = CARIBBEAN.box;
  if (lon >= w && lon <= e && lat >= s && lat <= n) return CARIBBEAN.name;
  return null;
}
