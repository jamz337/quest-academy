// A simple world map for Flag Finder's "fly it where it belongs" board: coarse outlines of the parts of the world in
// longitude / latitude, where each country sits, and which part of the world a point is in. Pure data and maths;
// the scene projects the outlines onto its board (stretched a little taller than a true map, so it reads on a phone).

/** The map's edges: from Alaska's edge to the date line, from the Arctic to Cape Horn. */
export const MAP_BOX = { lon0: -140, lon1: 180, lat0: 72, lat1: -56 };

/** A point as fractions across (u) and down (v) the map. */
export function toMap(lon, lat) {
  const u = (lon - MAP_BOX.lon0) / (MAP_BOX.lon1 - MAP_BOX.lon0);
  const v = (MAP_BOX.lat0 - Math.min(MAP_BOX.lat0, lat)) / (MAP_BOX.lat0 - MAP_BOX.lat1);
  return { u, v };
}
/** The reverse: fractions across and down back to longitude and latitude. */
export function fromMap(u, v) {
  return { lon: MAP_BOX.lon0 + u * (MAP_BOX.lon1 - MAP_BOX.lon0), lat: MAP_BOX.lat0 - v * (MAP_BOX.lat0 - MAP_BOX.lat1) };
}

